  telefono text,
  note text,
  bolla text,
  ddt text,
  vario text,
  bolla_url text,
  ddt_url text,
  vario_url text,
  bolla_path text,
  ddt_path text,
  vario_path text,
  bolla_mime text,
  ddt_mime text,
  vario_mime text,
  bolla_dati_b64 text,
  ddt_dati_b64 text,
  vario_dati_b64 text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
