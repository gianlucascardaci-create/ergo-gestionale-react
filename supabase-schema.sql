create table if not exists public.utenti_autorizzati (
  id bigint generated by default as identity primary key,
  username text not null unique,
  password text,
  ruolo text,
  nome text,
  email text,
  created_at timestamptz not null default now()
);

create index if not exists prodotti_noleggio_nome_idx on public.prodotti_noleggio(nome);
create index if not exists prodotti_noleggio_categoria_idx on public.prodotti_noleggio(categoria);
create index if not exists eventi_catering_data_idx on public.eventi_catering(data);
create index if not exists noleggi_inizio_idx on public.noleggi(inizio);

create or replace function public.ergo_touch_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists prodotti_noleggio_touch on public.prodotti_noleggio;
create trigger prodotti_noleggio_touch before update on public.prodotti_noleggio for each row execute function public.ergo_touch_updated_at();
drop trigger if exists eventi_catering_touch on public.eventi_catering;
create trigger eventi_catering_touch before update on public.eventi_catering for each row execute function public.ergo_touch_updated_at();
drop trigger if exists noleggi_touch on public.noleggi;
create trigger noleggi_touch before update on public.noleggi for each row execute function public.ergo_touch_updated_at();

alter table public.prodotti_noleggio enable row level security;
alter table public.eventi_catering enable row level security;
alter table public.noleggi enable row level security;
alter table public.utenti_autorizzati enable row level security;

