create table if not exists public.prodotti_noleggio (
  id bigint generated by default as identity primary key,
  codice text not null unique,
  nome text not null,
  categoria text,
  quantita integer not null default 0,
  posizione text,
  costo_noleggio numeric(12,2) not null default 0,
  note text,
  foto_path text,
  scheda_tecnica text,
  scheda_materiale text,
  scheda_colore text,
  scheda_dimensione text,
  scheda_note text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.eventi_catering (
  id bigint generated by default as identity primary key,
  client_id text,
  nome_evento text not null,
  data date,
  data_display text,
  location text,
  ospiti integer not null default 0,
  bambini integer not null default 0,
  staff integer not null default 0,
  note_tutti text,
  allegati_tutti jsonb not null default '[]'::jsonb,
  note_sala text,
  allegati_sala jsonb not null default '[]'::jsonb,
  note_cucina text,
  allegati_cucina jsonb not null default '[]'::jsonb,
  note_magazzino text,
  allegati_magazzino jsonb not null default '[]'::jsonb,
  allegati_privati jsonb not null default '[]'::jsonb,
  note_storico_tutti jsonb not null default '[]'::jsonb,
  note_storico_sala jsonb not null default '[]'::jsonb,
  note_storico_cucina jsonb not null default '[]'::jsonb,
  note_storico_magazzino jsonb not null default '[]'::jsonb,
  note_storico_admin jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create unique index if not exists eventi_catering_client_id_uidx on public.eventi_catering(client_id) where client_id is not null;

